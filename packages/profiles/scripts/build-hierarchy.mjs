/**
 * Generates `src/hierarchy.generated.ts` from the official Schema.org vocabulary.
 *
 *   node scripts/build-hierarchy.mjs
 *
 * The output is committed so the build never depends on the network. Rerun it by
 * hand when a new version of the vocabulary comes out.
 *
 * Only the type-to-parent edges are kept. Labels, comments and properties run to
 * megabytes and none of it helps resolve a profile.
 */
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const VOCAB_URL = 'https://schema.org/version/latest/schemaorg-current-https.jsonld';
const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'hierarchy.generated.ts');

// The vocabulary uses compact IRIs (`schema:Product`) and also carries classes
// from other vocabularies (`fibo-fnd-pas-pas:Product`, `dc:...`) that have to go.
const SCHEMA_PREFIX = 'schema:';
const isSchema = (iri) => typeof iri === 'string' && iri.startsWith(SCHEMA_PREFIX);

/** `schema:Product` -> `Product` */
const localName = (iri) => iri.slice(SCHEMA_PREFIX.length);

const asArray = (value) => (value === undefined ? [] : Array.isArray(value) ? value : [value]);

const response = await fetch(VOCAB_URL);
if (!response.ok) {
  console.error(`could not fetch the vocabulary: HTTP ${response.status}`);
  process.exit(1);
}
const vocab = await response.json();

const parents = {};
let classCount = 0;

for (const node of vocab['@graph'] ?? []) {
  const types = asArray(node['@type']);
  if (!types.includes('rdfs:Class')) continue;

  const id = node['@id'];
  if (!isSchema(id)) continue;
  classCount++;

  const supers = asArray(node['rdfs:subClassOf'])
    .map((s) => (typeof s === 'string' ? s : s?.['@id']))
    .filter(isSchema)
    .map(localName);

  if (supers.length) parents[localName(id)] = supers;
}

const sorted = Object.keys(parents).sort();
const body = sorted.map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(parents[k])},`).join('\n');

const file = `// GENERATED by scripts/build-hierarchy.mjs. Do not edit by hand.
// Source: ${VOCAB_URL}
// Classes in the vocabulary: ${classCount}. Classes with at least one parent: ${sorted.length}.

/** Direct parents of every Schema.org type. */
export const DIRECT_PARENTS: Record<string, readonly string[]> = {
${body}
};
`;

await writeFile(OUT, file, 'utf8');
console.log(`wrote ${sorted.length} of ${classCount} classes to ${OUT}`);
